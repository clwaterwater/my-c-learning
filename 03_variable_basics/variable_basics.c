#include <stdio.h>

int main(void)
{
	// ============================================
	// 变量：装数据的盒子
	// ============================================
	// 定义格式：数据类型  变量名;
	// 赋值格式：变量名 = 数据值;
	// ============================================

	// ---------- 1. 先定义，后赋值 ----------
	int a;
	a = 10;
	printf("%d\n", a);

	// ---------- 2. 定义时就知道值，可以一步到位 ----------
	int b = 20;
	printf("%d\n", b);

	// ============================================
	// 变量要遵守的五条规矩
	// ============================================

	// 规矩 1：一个变量里只能存一个值，新的会把旧的覆盖掉
	int x = 10;
	printf("x 一开始是：%d\n", x);
	x = 20;
	printf("x 赋值后是：%d\n", x);

	// 规矩 2：变量名不能重复（同一个范围内）
	// int x = 30;   ← 再定义一次会报错：error C2374 重定义

	// 规矩 3：一条语句可以定义多个变量（了解即可）
	int p = 10, q = 20, r = 30;
	printf("p=%d q=%d r=%d\n", p, q, r);

	// 规矩 4：变量在使用之前，一定要赋值
	// int un;
	// printf("%d", un);   ← 里面是随机垃圾数，warning C4700

	// 规矩 5：变量的作用范围（作用域）
	// 变量只在它所在的那一层大括号 {} 里管用，出了括号就不认识了。
	// 这个到函数那一章会再细讲。

	// ============================================
	// 练习 1：两个数相加
	// ============================================
	int c = 10;
	int d = 20;
	printf("直接算：%d\n", c + d);

	int e = c + d;
	printf("存起来再打印：%d\n", e);

	// ============================================
	// 练习 2：经常变的数据，就该用变量
	// ============================================

	// 微信余额：一开始 100 元，又收到 2 元
	int money = 100;
	money = money + 2;
	printf("余额：%d\n", money);

	// 游戏血量：初始 100，受伤 -80，回血 +60
	int blood = 100;
	int hurt = 80;
	int recover = 60;
	printf("剩余血量：%d\n", blood - hurt + recover);

	return 0;
}
