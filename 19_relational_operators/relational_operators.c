#include <stdio.h>

int main(void)
{
	// ============================================
	// 关系运算符（比较运算符）
	// ============================================
	// ==  是否等于      !=  是否不等于
	// >   是否大于      >=  是否大于等于
	// <   是否小于      <=  是否小于等于
	//
	// 结果只有两个值：成立是 1，不成立是 0。
	// C 语言里没有专门的「真 / 假」，1 就是真，0 就是假。
	// ============================================

	int a = 10;
	int b = 20;

	printf("a = %d, b = %d\n", a, b);
	printf("a == b  （是否等于）      ：%d\n", a == b);
	printf("a != b  （是否不等于）    ：%d\n", a != b);
	printf("a >  b  （是否大于）      ：%d\n", a > b);
	printf("a >= b  （是否大于等于）  ：%d\n", a >= b);
	printf("a <  b  （是否小于）      ：%d\n", a < b);
	printf("a <= b  （是否小于等于）  ：%d\n", a <= b);

	// ============================================
	// 新手头号陷阱：== 写成 =
	// ============================================
	// == 是「比较」：两边的值一样吗？
	// =  是「赋值」：把右边塞进左边去，不管原来是什么。
	//
	// if (a = 5)      ← 这不是「a 等于 5 吗」，而是「把 5 赋给 a」，
	//                   然后拿赋值后的 a（也就是 5）当判断条件。
	//                   5 不是 0，所以条件永远成立！
	//                   这种 bug 编译器有时会给警告，有时不会，特别难查。
	//
	// 正确写法：if (a == 5)
	// --------------------------------------------
	int n = 1;
	printf("\nn 原来是 %d\n", n);
	printf("写成 n = 99 会怎样：%d\n", n = 99);
	// 上面这句不是比较，是直接把 99 塞进 n 了！所以打印出 99
	printf("所以现在 n 已经变成 %d 了\n", n);

	return 0;
}
