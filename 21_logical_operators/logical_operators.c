#include <stdio.h>

int main(void)
{
	// ============================================
	// 逻辑运算符：&&  ||  !
	// ============================================
	// &&  与（and）：两边都成立，结果才是 1
	// ||  或（or） ：只要有一边成立，结果就是 1
	// !   非（not）：把结果反过来，1 变 0，0 变 1
	// ============================================

	printf("---------- 真值表 ----------\n");
	printf("1 && 1 = %d\n", 1 && 1);
	printf("1 && 0 = %d\n", 1 && 0);
	printf("0 && 1 = %d\n", 0 && 1);
	printf("0 && 0 = %d\n", 0 && 0);

	printf("1 || 1 = %d\n", 1 || 1);
	printf("1 || 0 = %d\n", 1 || 0);
	printf("0 || 1 = %d\n", 0 || 1);
	printf("0 || 0 = %d\n", 0 || 0);

	printf("!1 = %d\n", !1);
	printf("!0 = %d\n", !0);

	// ============================================
	// 短路求值：重点，考试和面试都爱考
	// ============================================
	// && 一旦左边是 0，右边根本不会执行（已经知道结果是 0 了，算了也白算）
	// || 一旦左边是 1，右边同样不会执行（已经知道结果是 1 了）
	// ============================================

	int count = 0;

	// 左边是 0，所以右边的 ++count 被跳过了
	int r1 = (0 && (++count));
	printf("\n(0 && ++count) 结果 r1=%d，count=%d  → 右边没执行\n", r1, count);

	// 左边是 1，所以右边的 ++count 会执行
	int r2 = (1 && (++count));
	printf("(1 && ++count) 结果 r2=%d，count=%d  → 右边执行了\n", r2, count);

	// || 反过来：左边是 1 就短路
	int cnt2 = 0;
	int r3 = (1 || (++cnt2));
	printf("(1 || ++cnt2)  结果 r3=%d，cnt2=%d  → 右边没执行\n", r3, cnt2);

	// ============================================
	// 短路的实际用途：把「先检查」放在左边保护右边
	// ============================================
	// 比如下面这句，如果 num 是 0，左边不成立，右边的除法就不会被执行，
	// 从而避免了除零崩溃。
	int num = 0;
	if (num != 0 && 100 / num > 5)
	{
		printf("100/num 大于 5\n");
	}
	else
	{
		printf("num 是 0（或不够大），右边那句除法根本没跑\n");
	}

	// ============================================
	// 应用场景
	// 1. 登录：用户名和密码都对 → 用 &&
	// 2. 登录方式：扫码 OR 账号密码，任选一种 → 用 ||
	// 3. 会员 | 非会员 → 用 !
	// ============================================

	return 0;
}
