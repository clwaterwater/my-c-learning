#include <stdio.h>

int main(void)
{
	// ============================================
	// if 嵌套：在一个 if（或 else）的里面，再写一层 if
	// ============================================
	// 什么时候需要嵌套？
	// 当第一个条件筛完之后，还要在通过的那批里再细分一次。
	// ============================================

	int a, b, c, d;
	a = 1, b = 1, c = 2, d = 3;

	if (a != b)
	{
		printf("打游戏\n");
	}
	else
	{
		// 进到这里，说明 a == b
		// 现在在「a 等于 b」的前提下，再用 c 和 d 判断一次
		if (c == d + 1 || c == d - 1)
		{
			// c=2, d=3 → d-1 正好等于 2，所以这一支成立
			printf("看电影\n");
		}
		else
		{
			printf("打游戏\n");
		}
	}

	// ============================================
	// 拆开看每一步
	// ============================================
	printf("\n--- 拆开验证 ---\n");
	printf("a=%d, b=%d, c=%d, d=%d\n", a, b, c, d);
	printf("a != b              ：%d  → 不成立，所以走 else\n", a != b);
	printf("c == d + 1          ：%d\n", c == d + 1);
	printf("c == d - 1          ：%d  → d-1=2，c=2，成立\n", c == d - 1);
	printf("两者用 || 连起来    ：%d  → 所以输出「看电影」\n", c == d + 1 || c == d - 1);

	// ============================================
	// 写法建议
	// ============================================
	// 1. if / else 哪怕只有一句，也建议加大括号 {}，
	//    不然以后往里加第二句时容易出事。
	// 2. else if 其实就是「在 else 里再套一层 if」的简写，
	//    一层层的 if-else if-else 链，本质上和这里的嵌套是一回事。
	// ============================================

	return 0;
}
