#include <stdio.h>

int main(void)
{
	// ============================================
	// printf 与占位符
	// ============================================
	// printf 是个翻译官：你给它一个「坑」（占位符）和一个「值」，
	// 它负责把值翻译成字，填进坑里印出来。
	//
	// 常用占位符：
	//   %d  整数 int
	//   %ld 长整数 long          %lld 超长整数 long long
	//   %f  小数 float           %lf 小数 double
	//   %c  单个字符 char
	//   %s  一串字符（字符串）
	//   %zu sizeof 算出来的字节数
	// ============================================

	// ---------- 1. 输出整数 %d ----------
	printf("整数：%d\n", 18);

	// ---------- 2. 输出小数 %f ----------
	printf("小数：%f\n", 1.93);
	// 默认印 6 位小数。想只要两位，在 % 和 f 中间加个 .2
	printf("小数保留两位：%.2f\n", 1.93);

	// ---------- 3. 输出字符 %c ----------
	printf("字符：%c\n", 'A');
	// 单引号 = 单个字符；双引号 = 一串字符，别混

	// ---------- 4. 输出字符串 %s ----------
	// 第一种：直接把话写进去
	printf("HelloWorld!\n");
	// 第二种：结合占位符
	printf("My name is:%s\n", "pear");

	// ---------- 5. 一条 printf 里塞多个占位符 ----------
	// 顺序必须对应：第一个坑配第一个值，第二个坑配第二个值
	printf("姓名:%s.性别：%s\n", "梨", "女");
	printf("年龄：%d.身高：%f\n", 18, 1.55);
	printf("我的学校是:%s\n", "桂林十八中");

	// ---------- 6. 坑和数据对不上会怎样 ----------
	// printf("%d", 1.93);   ← 错：%d 要整数，给的是小数，印出来是乱码数字
	// printf("%f", 18);     ← 错：反过来也一样
	// 这两个 warning 不一定拦得住，所以自己要对得上。

	// ---------- 7. 换行 \n ----------
	// \n 是换行符。习惯上放在格式串最后，一次换一行。
	printf("这一行后面会换行\n");
	printf("这是新的一行\n");

	return 0;
}
