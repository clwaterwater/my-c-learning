#include <stdio.h>

int main(void)
{
	// ============================================
	// 自增 ++  和  自减 --
	// ============================================
	// ++ 让变量自己的值加 1，-- 让变量自己的值减 1。
	// 唯一的考点是：写在变量「前面」还是「后面」，效果不一样。
	//
	// 口诀：
	//   后缀 a++  —— 先把 a 原来的值拿出来用，用完 a 再自己 +1（先用后加）
	//   前缀 ++a  —— a 先自己 +1，再把加完之后的值拿去用（先加后用）
	// ============================================

	// ---------- 1. 后缀 ++：先用后加 ----------
	int a = 10;
	int b = a++;
	printf("后缀：int b = a++;      →  b=%d, a=%d\n", b, a);
	// b 拿到的是 10（原来的值），之后 a 才变成 11

	// ---------- 2. 前缀 ++：先加后用 ----------
	int c = 10;
	int d = ++c;
	printf("前缀：int d = ++c;      →  d=%d, c=%d\n", d, c);
	// c 先自己加到 11，d 拿到的就是加完之后的 11

	// ---------- 3. 自减同理 ----------
	int e = 10;
	int f = e--;
	printf("后缀：int f = e--;      →  f=%d, e=%d\n", f, e);

	int g = 10;
	int h = --g;
	printf("前缀：int h = --g;      →  h=%d, g=%d\n", h, g);

	// ---------- 4. 单独成一条语句时，前后缀没区别 ----------
	// 没有人去「用」这个值，所以先加后加结果一样，都只是加了 1。
	int i = 10;
	i++;
	printf("i++ 单独用：i=%d\n", i);
	++i;
	printf("++i 单独用：i=%d\n", i);

	// ---------- 5. 放进 printf 里看差别最直观 ----------
	// 注意这里必须拆成三句写，不能写成 printf("%d", x++, x)。
	// 原因见 notes/未定义行为UB.md —— 那样写是未定义行为，结果不保证。
	int x = 5;
	printf("打印 x++ 的结果是：");
	printf("%d", x++);
	printf("，这句执行完 x 变成：%d\n", x);

	int y = 5;
	printf("打印 ++y 的结果是：");
	printf("%d", ++y);
	printf("，这句执行完 y 变成：%d\n", y);

	// ---------- 6. 最常见的用法：循环里数数 ----------
	int count = 0;
	count++;
	count++;
	count++;
	printf("连续三次 count++ 之后：count=%d\n", count);

	return 0;
}
