#include <stdio.h>

int main(void)
{
	// ============================================
	// 复合赋值运算符：+=  -=  *=  /=  %=
	// ============================================
	// 含义：把左边和右边算一遍，结果塞回左边去。
	//       a += b;  等价于  a = a + b;
	// 注意：右边那个变量本身不受影响，只有左边会被改。
	// ============================================

	int a = 10;
	int b = 20;

	a += b;                                    // a = a + b → a 变成 30
	printf("a += b  之后：a=%d, b=%d\n", a, b);  // b 还是 20，没动

	a -= 5;                                    // a = a - 5
	printf("a -= 5  之后：a=%d\n", a);

	a *= 2;                                    // a = a * 2
	printf("a *= 2  之后：a=%d\n", a);

	a /= 4;                                    // a = a / 4
	printf("a /= 4  之后：a=%d\n", a);
	// 整数除法会截断，除不尽的部分直接扔掉

	a %= 5;                                    // a = a % 5
	printf("a %%= 5  之后：a=%d\n", a);
	// printf 里 %% 表示打印一个真正的百分号

	// --------------------------------------------
	// 提醒：/= 和 %= 的右边同样不能是 0，会直接崩。
	// int z = 10;
	// z /= 0;      ← 这样写程序会挂掉
	// --------------------------------------------

	return 0;
}
