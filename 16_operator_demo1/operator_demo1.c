#include<stdio.h>

int main()
{
	//+-*
	//数字直接进行计算
	printf("%d\n",3+2);
	printf("%d\n",3-2);
	printf("%d\n",3*2);
	
	printf("%.2lf\n",1.1+1.01);
	printf("%.2lf\n",1.1-1.01);
	printf("%.2lf\n",1.1*1.01);

	//变量进行计算
	int a = 3;
	int b = 4;
	printf("%d\n",a+b);

	//除法/
	printf("%d\n",10/2);
	//取余%
	printf("%d\n",10%2);
	printf("%d\n",10%3);

	//通用细节（+-*/%）：
	// 1.整数计算，结果一定是整数
	// printf("%d\n",10/3);结果为3
	
	//2.小数计算，结果一定为小数(只要有一个是小数即可)
	// printf("%lf\n",10.0+3.0);13.0

	//3.小数参与计算，结果有可能不精确
	//printf("%.20lf\n",10.0/3.0);

	//除法的细节
	//1.不能除以0

	//取余的细节：
	//1.运算的数据必须全部都是整数
	//2.获取余数的正负，是跟第一个数字保持一致的
	printf("%d\n", 10%3);//1
	printf("%d\n", -10%3);//-1
	printf("%d\n", 10%-3);//1
	//3.不能除于0


}